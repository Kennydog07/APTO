/**
 * Merges the AI tools into the main apto-pro.com site (the repo root). Run from the repo root:
 *
 *   node ai-tools/scripts/apply-merge-kit.mjs
 *
 * Safe to run more than once. It:
 *  1. copies ai-tools/merge-kit/functions/ai-*.mts into ./functions/
 *  2. sets the build command in ./netlify.toml [build] (builds the tools into ./ai/)
 *  3. appends the /ai redirects, headers and function settings to ./netlify.toml
 *  4. adds the tools' sitemap to ./robots.txt
 *  5. ignores the ./ai/ build output in ./.gitignore
 *  6. adds pdf-parse to ./package.json (the CV reader needs it installed: native add-on)
 * It never changes or removes anything belonging to the main site.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// --repo <dir> is only for tests; normally the main site is the folder above ai-tools/.
const repoArg = process.argv.indexOf('--repo');
const repo = repoArg > 0 ? path.resolve(process.argv[repoArg + 1]) : path.resolve(toolsDir, '..');
const kit = path.join(toolsDir, 'merge-kit');
const MARK = '# >>> APTO AI tools (/ai) >>>';
const BUILD_CMD =
  'npm ci --prefix ai-tools && AI_TOOLS_OUT_DIR=../ai npm run build --prefix ai-tools && npm run build:functions --prefix ai-tools';
const done = [];

// 1. function wrappers
const fnDir = path.join(repo, 'functions');
fs.mkdirSync(fnDir, { recursive: true });
for (const f of fs.readdirSync(path.join(kit, 'functions'))) {
  const target = path.join(fnDir, f);
  if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').includes('GENERATED by ai-tools')) {
    throw new Error(`functions/${f} already exists and is not an ai-tools wrapper – stopping`);
  }
  fs.copyFileSync(path.join(kit, 'functions', f), target);
}
done.push('copied function wrappers into functions/');

// 2 + 3. netlify.toml
const tomlPath = path.join(repo, 'netlify.toml');
let toml = fs.readFileSync(tomlPath, 'utf8');
const build = /^\[build\][^[]*/m.exec(toml);
if (!build) throw new Error('netlify.toml has no [build] section');
if (/^\s*command\s*=/m.test(build[0])) {
  if (!build[0].includes('ai-tools')) {
    throw new Error(
      'netlify.toml [build] already has a command – add the ai-tools build to it by hand:\n  ' +
        BUILD_CMD,
    );
  }
} else {
  toml = toml.replace(/^\[build\]\n/m, `[build]\n  command = "${BUILD_CMD}"\n`);
  done.push('set the build command in netlify.toml');
}
if (/^\[build\.environment\]/m.test(toml) && !toml.includes(MARK)) {
  throw new Error(
    'netlify.toml already has [build.environment] – merge the block in merge-kit/netlify-main-site.toml by hand',
  );
}
if (!toml.includes(MARK)) {
  toml = toml.trimEnd() + '\n' + fs.readFileSync(path.join(kit, 'netlify-main-site.toml'), 'utf8');
  done.push('appended /ai settings to netlify.toml');
}
fs.writeFileSync(tomlPath, toml);

// 4. robots.txt
const robotsPath = path.join(repo, 'robots.txt');
if (fs.existsSync(robotsPath)) {
  let robots = fs.readFileSync(robotsPath, 'utf8');
  const main = /^Sitemap:\s*(https?:\/\/[^/\s]+)/m.exec(robots);
  const origin = main ? main[1] : 'https://apto-pro.com';
  const line = `Sitemap: ${origin}/ai/sitemap.xml`;
  if (!robots.includes('/ai/sitemap.xml')) {
    const rules = 'Disallow: /ai/t/\nDisallow: /ai/api/\n';
    // Put the rules inside the existing "User-agent: *" group; add our sitemap at the end.
    robots = /^User-agent:\s*\*\s*$/m.test(robots)
      ? robots.replace(/^(User-agent:\s*\*\s*\n)/m, `$1${rules}`)
      : `User-agent: *\n${rules}\n` + robots;
    robots = robots.trimEnd() + `\n${line}\n`;
    fs.writeFileSync(robotsPath, robots);
    done.push('added the /ai sitemap to robots.txt');
  }
}

// 5. .gitignore
const giPath = path.join(repo, '.gitignore');
const gi = fs.existsSync(giPath) ? fs.readFileSync(giPath, 'utf8') : '';
if (!/^\/ai\/$/m.test(gi)) {
  fs.writeFileSync(giPath, gi.trimEnd() + '\n# AI tools build output\n/ai/\n');
  done.push('ignored the /ai/ build output in .gitignore');
}

// 6. pdf-parse in the main site's package.json (same version as the tools use)
const toolsPkg = JSON.parse(fs.readFileSync(path.join(toolsDir, 'package.json'), 'utf8'));
const rootPkgPath = path.join(repo, 'package.json');
const rootPkg = JSON.parse(fs.readFileSync(rootPkgPath, 'utf8'));
rootPkg.dependencies ??= {};
if (rootPkg.dependencies['pdf-parse'] !== toolsPkg.dependencies['pdf-parse']) {
  rootPkg.dependencies['pdf-parse'] = toolsPkg.dependencies['pdf-parse'];
  fs.writeFileSync(rootPkgPath, JSON.stringify(rootPkg, null, 2) + '\n');
  done.push('added pdf-parse to package.json (run `npm install` to update package-lock.json)');
}

console.log(done.length ? done.map((d) => `✓ ${d}`).join('\n') : 'Already merged – nothing to do.');
console.log(
  '\nNext: set the AI_TOOLS_* environment variables in Netlify (see ai-tools/MERGE_INTO_APTO_TOOLS.md).',
);
