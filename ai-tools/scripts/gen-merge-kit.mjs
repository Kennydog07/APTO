/**
 * Generates merge-kit/functions/*.mts: one tiny wrapper per tool function, for the main
 * apto-pro.com site's `functions/` folder. Each wrapper re-exports the pre-bundled handler
 * from ai-tools/functions-dist/ (built by `npm run build:functions` during the main site's
 * build) and repeats its `config` as a literal (Netlify reads config statically from the
 * entry file, so it can't be re-exported).
 *
 *   npm run merge-kit            (writes the files)
 *   npm run merge-kit -- --check (fails if they're out of date; used by the unit tests)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'netlify', 'functions');
const outDir = path.join(root, 'merge-kit', 'functions');

export function buildWrappers() {
  const files = fs
    .readdirSync(srcDir)
    .filter((f) => f.endsWith('.ts'))
    .sort();
  return files.map((file) => {
    const name = file.replace(/\.ts$/, '');
    const src = fs.readFileSync(path.join(srcDir, file), 'utf8');
    const m = /export const config: Config = (\{[^\n]*\});/.exec(src);
    if (!name.startsWith('ai-')) throw new Error(`${file}: tool functions must be named ai-*`);
    if (!m && !name.endsWith('-background'))
      throw new Error(`${file}: missing one-line config export`);
    const lines = [
      '// GENERATED by ai-tools/scripts/gen-merge-kit.mjs – do not edit by hand.',
      "// Copy into the main site's functions/ folder (see ai-tools/MERGE_INTO_APTO_TOOLS.md).",
      `export { default } from '../ai-tools/functions-dist/${name}.mjs';`,
    ];
    if (m) lines.push(`export const config = ${m[1]};`);
    return { file: `${name}.mts`, content: lines.join('\n') + '\n' };
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const wrappers = buildWrappers();
  if (process.argv.includes('--check')) {
    const stale = wrappers.filter(
      (w) =>
        !fs.existsSync(path.join(outDir, w.file)) ||
        fs.readFileSync(path.join(outDir, w.file), 'utf8') !== w.content,
    );
    const extra = fs.existsSync(outDir)
      ? fs.readdirSync(outDir).filter((f) => !wrappers.some((w) => w.file === f))
      : [];
    if (stale.length || extra.length) {
      console.error(
        'merge kit out of date:',
        [...stale.map((w) => w.file), ...extra].join(', '),
        '– run `npm run merge-kit`',
      );
      process.exit(1);
    }
    console.log('merge kit up to date');
  } else {
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });
    for (const w of wrappers) fs.writeFileSync(path.join(outDir, w.file), w.content);
    console.log(`wrote ${wrappers.length} wrappers to merge-kit/functions/`);
  }
}
